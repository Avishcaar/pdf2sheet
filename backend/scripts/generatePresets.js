import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { PDFDocument, StandardFonts, rgb } from 'pdf-lib';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const basePdfPath = path.join(__dirname, '../uploads/basicapi.pdf');
const outputDirFrontend = path.join(__dirname, '../../frontend/public/samples');
const outputDirBackend = path.join(__dirname, '../uploads/samples');

if (!fs.existsSync(outputDirFrontend)) fs.mkdirSync(outputDirFrontend, { recursive: true });
if (!fs.existsSync(outputDirBackend)) fs.mkdirSync(outputDirBackend, { recursive: true });

async function createSampleInvoice({ filename, vendorName, invoiceNumber, invoiceDate, dueDate, totalAmount }) {
    const baseBytes = fs.readFileSync(basePdfPath);
    const doc = await PDFDocument.load(baseBytes);
    
    // We only keep the 1st page
    while (doc.getPageCount() > 1) {
        doc.removePage(1);
    }

    const page = doc.getPages()[0];
    const { width, height } = page.getSize();

    // Draw white rectangle over the old table of contents
    page.drawRectangle({
        x: 0,
        y: 0,
        width,
        height,
        color: rgb(1, 1, 1)
    });

    const bold = await doc.embedFont(StandardFonts.HelveticaBold);
    const regular = await doc.embedFont(StandardFonts.Helvetica);

    // Header Banner
    page.drawText(vendorName, { x: 50, y: 740, size: 22, font: bold, color: rgb(0.1, 0.1, 0.15) });
    page.drawText('OFFICIAL COMMERCIAL INVOICE', { x: 50, y: 720, size: 9, font: bold, color: rgb(0.5, 0.5, 0.6) });

    // Divider Line
    page.drawLine({
        start: { x: 50, y: 705 },
        end: { x: 545, y: 705 },
        thickness: 1.5,
        color: rgb(0.85, 0.85, 0.9)
    });

    // Metadata Grid
    page.drawText('Invoice Number:', { x: 50, y: 670, size: 11, font: regular, color: rgb(0.4, 0.4, 0.45) });
    page.drawText(invoiceNumber, { x: 160, y: 670, size: 11, font: bold, color: rgb(0.1, 0.1, 0.15) });

    page.drawText('Invoice Date:', { x: 50, y: 645, size: 11, font: regular, color: rgb(0.4, 0.4, 0.45) });
    page.drawText(invoiceDate, { x: 160, y: 645, size: 11, font: regular, color: rgb(0.1, 0.1, 0.15) });

    page.drawText('Due Date:', { x: 50, y: 620, size: 11, font: regular, color: rgb(0.4, 0.4, 0.45) });
    page.drawText(dueDate, { x: 160, y: 620, size: 11, font: regular, color: rgb(0.1, 0.1, 0.15) });

    // Table Header
    page.drawRectangle({
        x: 50,
        y: 565,
        width: 495,
        height: 25,
        color: rgb(0.95, 0.95, 0.98)
    });
    page.drawText('Description', { x: 60, y: 573, size: 10, font: bold, color: rgb(0.3, 0.3, 0.4) });
    page.drawText('Amount (USD)', { x: 440, y: 573, size: 10, font: bold, color: rgb(0.3, 0.3, 0.4) });

    // Line Item
    page.drawText('Automated Software Services & API Usage', { x: 60, y: 540, size: 10, font: regular, color: rgb(0.2, 0.2, 0.2) });
    page.drawText(`$${totalAmount}`, { x: 450, y: 540, size: 10, font: regular, color: rgb(0.2, 0.2, 0.2) });

    // Total Amount Box
    page.drawRectangle({
        x: 320,
        y: 470,
        width: 225,
        height: 45,
        color: rgb(0.94, 0.96, 1.0)
    });
    page.drawText('Total Amount Due:', { x: 335, y: 492, size: 10, font: regular, color: rgb(0.2, 0.3, 0.5) });
    page.drawText(`$${totalAmount}`, { x: 445, y: 488, size: 14, font: bold, color: rgb(0.1, 0.2, 0.6) });

    // Footer
    page.drawText('Thank you for your business. Generated by PDF2Sheet Automation Engine.', {
        x: 50,
        y: 80,
        size: 9,
        font: regular,
        color: rgb(0.5, 0.5, 0.55)
    });

    const pdfBytes = await doc.save();
    fs.writeFileSync(path.join(outputDirFrontend, filename), pdfBytes);
    fs.writeFileSync(path.join(outputDirBackend, filename), pdfBytes);
    console.log(`Generated ${filename} (${pdfBytes.length} bytes)`);
}

async function run() {
    await createSampleInvoice({
        filename: 'stripe-invoice.pdf',
        vendorName: 'Stripe Payments',
        invoiceNumber: 'INV-STRIPE-8842',
        invoiceDate: '12-01-2026',
        dueDate: '26-01-2026',
        totalAmount: '1,420.00'
    });

    await createSampleInvoice({
        filename: 'aws-invoice.pdf',
        vendorName: 'AWS Cloud Services',
        invoiceNumber: 'INV-AWS-2026-90',
        invoiceDate: '15-01-2026',
        dueDate: '30-01-2026',
        totalAmount: '2,845.50'
    });

    await createSampleInvoice({
        filename: 'github-invoice.pdf',
        vendorName: 'GitHub Enterprise',
        invoiceNumber: 'INV-GH-77319',
        invoiceDate: '18-01-2026',
        dueDate: '01-02-2026',
        totalAmount: '420.00'
    });

    console.log('All 3 sample preset invoice PDFs generated successfully!');
}

run();
